/* =========================================================================
 * common.h - 课堂控制软件 公共协议定义
 * (仿极域电子教室架构的教学演示实现, 仅用于学习/课堂教学)
 *
 * 总体架构 (对应极域的等效做法):
 *   1. UDP 发现通道: 教师端周期广播自身存在(=极域"教师频道广播"),
 *      学生端据此得知教师 IP 后发送登录/心跳报文(=极域"学生登录")
 *   2. TCP 控制通道: 每个学生与教师端保持一条长连接, 教师在此下发
 *      锁屏/消息/广播开关/文件/关机等命令(=极域的命令通道)
 *   3. UDP 组播数据通道: 屏幕广播使用组播一发多收(=极域核心省带宽设计,
 *      教师端 截图->编码->发送 三级流水, 帧拆小片, 学生端重组渲染)
 * ========================================================================= */
#ifndef CLASSCTRL_COMMON_H
#define CLASSCTRL_COMMON_H

#define UDP_PORT    15555            /* 教师端发现广播端口 (教师->学生, 仅学生绑定) */
#define STU_UDP_PORT 15556           /* 学生登录/心跳上报端口 (学生->教师, 仅教师绑定)
                                          端口分离: 避免 Windows 上 SO_REUSEADDR 共享端口时
                                          单播只投递给最后绑定者, 导致同机测试学生收不到广播 */
#define TCP_PORT    15666            /* 控制通道 (TCP, 学生->教师主动连接) */
#define REV_PORT    15670            /* 反向接入端口 (教师扫描子网后主动连学生; 不依赖广播) */
#define DEMO_PORT   15667            /* 屏幕广播组播端口 (UDP) */
#define MCAST_GROUP "239.10.10.10"   /* 屏幕广播组播组 (同网段有效) */
#define RDP_PORT    15668            /* 远程桌面通道 (TCP, 学生->教师连接; 教师在此下行注入事件) */
#define RDP_MAGIC   0x52434150u      /* 'RCAP' 远程桌面帧魔数 */

/* 屏幕广播小片: [u32 魔数][u32 帧序号][u32 片号][u32 总片数][u32 帧字节]
 *             [u32 宽][u32 高] 共 28 字节 + 像素数据 (<=1400 字节, 贴合 MTU) */
#define CHK_MAGIC      0x43434831u   /* 'CCH1' */
#define CHUNK_PAYLOAD  1400

/* 控制通道帧格式: [u32 len][payload]
 * payload = 以 '\n' 结尾的 ASCII 命令头 + 可选二进制数据
 * 教师->学生: LOCK / UNLOCK / MSG|<字节数> / DEMO_START / DEMO_STOP
 *             FILE|<文件名>|<大小> / SHUTDOWN / REBOOT
 * 学生->教师: HI|<主机名> / ACK|<命令>                                */

#endif /* CLASSCTRL_COMMON_H */
